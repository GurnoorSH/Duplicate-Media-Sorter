#!/usr/bin/env python3
"""
Safety-first wrapper around duplicate_images' find-dups command.

find-dups computes and caches perceptual hashes and reports matching groups.
The wrapper then splits each match into byte-identical copies and merely
similar images, keeps the best copy, and only acts on identical copies unless
``--include-similar`` is given. Quarantine runs write the same restorable
manifest as the desktop app.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Sequence

import media_sorter


ALGORITHMS = (
    "phash",
    "dhash",
    "ahash",
    "whash",
    "colorhash",
    "dhash_vertical",
    "phash_simple",
    "crop_resistant",
)
MODES = ("dry-run", "quarantine", "delete")
HASH_DB_SUFFIXES = (".json", ".pickle")
HEIC_SUFFIXES = {".heic", ".heif", ".hif"}
DEFAULT_CACHE = Path("photo_hashes.json")

HEIF_BOOTSTRAP = """\
# Generated by dedup_manager.py.
# Ensures Pillow can decode HEIC/HEIF files inside the find-dups subprocess.
try:
    from pillow_heif import register_heif_opener

    register_heif_opener()
except Exception:
    pass
"""


@dataclass(frozen=True)
class DedupConfig:
    target: Path
    cache: Path = DEFAULT_CACHE
    mode: str = "dry-run"
    quarantine_dir: Path | None = None
    algorithm: str = "phash"
    hash_size: int = 8
    find_dups_executable: str = "find-dups"
    progress: bool = True
    parallel: bool = True
    parallel_workers: int | None = None
    exclude_dirs: tuple[str, ...] = field(default_factory=tuple)
    max_image_pixels: int | None = None
    yes: bool = False
    print_command_only: bool = False
    include_similar: bool = False


def positive_int(raw_value: str) -> int:
    try:
        value = int(raw_value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("must be an integer") from exc
    if value <= 0:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return value


def existing_target(raw_value: str) -> Path:
    path = Path(raw_value).expanduser()
    if not path.exists():
        raise argparse.ArgumentTypeError(f"target does not exist: {path}")
    return path


def path_is_relative_to(child: Path, parent: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
    except ValueError:
        return False
    return True


def normalize_cache_path(cache: Path) -> Path:
    cache = cache.expanduser()
    if cache.suffix.lower() not in HASH_DB_SUFFIXES:
        suffixes = ", ".join(HASH_DB_SUFFIXES)
        raise ValueError(f"cache path must end with one of: {suffixes}")
    return cache


def default_quarantine_dir(target: Path) -> Path:
    target = target.resolve()
    target_name = target.stem if target.is_file() else target.name
    if not target_name:
        target_name = "photo_library"
    return target.parent / f"{target_name}_quarantine"


def digest_cache_path(cache: Path) -> Path:
    return cache.with_name(f"{cache.stem}_digests.json")


def build_find_dups_command(config: DedupConfig, find_dups: Sequence[str] | None = None) -> list[str]:
    """Build the hashing command. find-dups only reports groups; this script
    performs every move or delete itself."""
    if config.mode not in MODES:
        raise ValueError(f"unsupported mode: {config.mode}")
    cache = normalize_cache_path(config.cache)
    cmd = [
        *(find_dups or [config.find_dups_executable]),
        str(config.target),
    ]

    if config.parallel:
        cmd.append("--parallel")
        if config.parallel_workers is not None:
            cmd.append(str(config.parallel_workers))

    if config.progress:
        cmd.append("--progress")

    cmd.extend(
        [
            "--algorithm",
            config.algorithm,
            "--hash-size",
            str(config.hash_size),
            "--hash-db",
            str(cache),
            "--group",
        ]
    )

    if config.exclude_dirs:
        cmd.append("--exclude-dir")
        cmd.extend(config.exclude_dirs)

    if config.max_image_pixels is not None:
        cmd.extend(["--max-image-pixels", str(config.max_image_pixels)])

    # find-dups' own move/delete actions only touch one file per group and
    # cannot tell identical copies from similar shots, so it just reports.
    cmd.extend(["--on-equal", "quote"])
    return cmd


def shell_display(cmd: Sequence[str]) -> str:
    if os.name == "nt":
        return subprocess.list2cmdline(list(cmd))

    import shlex

    return shlex.join(cmd)


def find_heic_files(target: Path, limit: int = 5) -> list[Path]:
    target = target.resolve()
    matches: list[Path] = []
    if target.is_file():
        return [target] if target.suffix.lower() in HEIC_SUFFIXES else []

    def on_walk_error(error: OSError) -> None:
        print(f"Warning: could not read directory during HEIC preflight: {error}", file=sys.stderr)

    for root, _dirs, files in os.walk(target, onerror=on_walk_error):
        root_path = Path(root)
        for filename in files:
            candidate = root_path / filename
            if candidate.suffix.lower() in HEIC_SUFFIXES:
                matches.append(candidate)
                if len(matches) >= limit:
                    return matches
    return matches


def ensure_heif_support(required: bool) -> bool:
    try:
        from pillow_heif import register_heif_opener
    except ImportError:
        if required:
            raise RuntimeError(
                "HEIC/HEIF files were found, but pillow-heif is not installed. "
                "Install dependencies with: python -m pip install -r requirements.txt"
            )
        return False

    register_heif_opener()
    return True


def write_heif_bootstrap(runtime_dir: Path) -> Path:
    runtime_dir.mkdir(parents=True, exist_ok=True)
    sitecustomize = runtime_dir / "sitecustomize.py"
    if not sitecustomize.exists() or sitecustomize.read_text(encoding="utf-8") != HEIF_BOOTSTRAP:
        sitecustomize.write_text(HEIF_BOOTSTRAP, encoding="utf-8")
    return runtime_dir.resolve()


def confirm_delete(target: Path, count: int) -> None:
    response = input(
        f"WARNING: delete mode permanently removes {count} duplicate files under "
        f"'{target}'. Type DELETE to continue: "
    )
    if response.strip() != "DELETE":
        print("Operation aborted.")
        raise SystemExit(0)


def validate_environment(config: DedupConfig) -> tuple[list[str], dict[str, str]]:
    find_dups = media_sorter.find_dups_command_prefix(config.find_dups_executable)
    if find_dups is None:
        raise RuntimeError(
            f"Could not find '{config.find_dups_executable}'. "
            "Install dependencies with: python -m pip install -r requirements.txt"
        )

    cache = normalize_cache_path(config.cache)
    cache_parent = cache.parent
    if str(cache_parent) not in ("", "."):
        cache_parent.mkdir(parents=True, exist_ok=True)

    heic_examples = find_heic_files(config.target)
    heif_bootstrap_dir: Path | None = None
    if heic_examples:
        ensure_heif_support(required=True)
        heif_bootstrap_dir = write_heif_bootstrap(Path(__file__).with_name(".dedup_runtime"))
        sample = ", ".join(str(path) for path in heic_examples[:3])
        print(f"HEIC support enabled for find-dups subprocess. Found examples: {sample}", flush=True)

    return find_dups, media_sorter.find_dups_environment(heif_bootstrap_dir)


def format_size(value: int) -> str:
    size = float(value)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.2f} {unit}"
        size /= 1024
    return f"{value} B"


def print_report(groups: Sequence[media_sorter.DuplicateGroup], include_similar: bool) -> None:
    for index, group in enumerate(groups, start=1):
        if group.keeper_path is None:
            size = group.items[0].size
            detail = "empty file (0 bytes)" if size == 0 else f"{format_size(size)}, every byte is zero"
            print(f"\nGroup {index} [EMPTY, no data]: {detail}")
            for item in group.duplicates:
                print(f"MOVE {item.path}")
            continue
        kind = "IDENTICAL" if group.exact else "SIMILAR, review"
        print(f"\nGroup {index} [{kind}]: {len(group.items)} files, {format_size(group.reclaimable_bytes)} reclaimable")
        print(f"KEEP {group.keeper_path}")
        verb = "MOVE" if group.exact or include_similar else "LOOK"
        for item in group.duplicates:
            print(f"{verb} {item.path}")

    empty = [group for group in groups if group.keeper_path is None]
    exact = [group for group in groups if group.exact and group.keeper_path is not None]
    similar = [group for group in groups if not group.exact]
    for label, chosen in (("Identical", exact), ("Similar", similar)):
        files = sum(len(group.duplicates) for group in chosen)
        size = sum(group.reclaimable_bytes for group in chosen)
        print(f"{label} groups: {len(chosen)} ({files} extra files, {format_size(size)})")
    print(f"Empty or zero-filled photos: {len(empty)} ({format_size(sum(group.reclaimable_bytes for group in empty))})")
    if similar and not include_similar:
        print("Similar groups are reported only. Review them in the desktop app, or pass --include-similar to act on them.")


def print_progress(progress: media_sorter.ScanProgress) -> None:
    if progress.warning:
        print(f"Warning: {progress.message}", file=sys.stderr, flush=True)
    elif progress.current is not None and progress.total and (progress.current % 1000 == 0 or progress.current == progress.total):
        print(f"{progress.message} ({progress.current}/{progress.total})", file=sys.stderr, flush=True)


def delete_duplicates(groups: Sequence[media_sorter.DuplicateGroup]) -> tuple[int, int]:
    deleted = failed = 0
    for group in groups:
        if group.keeper_path is not None and not group.keeper_path.exists():
            print(f"Skipping group: kept original is missing: {group.keeper_path}", file=sys.stderr)
            continue
        for item in group.duplicates:
            try:
                item.path.unlink()
            except OSError as exc:
                failed += 1
                print(f"Could not delete {item.path}: {exc}", file=sys.stderr)
            else:
                deleted += 1
                print(f"Deleted {item.path}")
    return deleted, failed


def run_deduplication(config: DedupConfig) -> int:
    find_dups, env = validate_environment(config)
    cmd = build_find_dups_command(config, find_dups)
    cache = normalize_cache_path(config.cache)
    quarantine_dir = (config.quarantine_dir or default_quarantine_dir(config.target)).resolve()

    print(f"Mode: {config.mode}", flush=True)
    print(f"Hash cache: {cache} ({'reusing' if cache.exists() else 'creating'})", flush=True)
    if config.mode == "quarantine":
        print(f"Quarantine: {quarantine_dir}", flush=True)
    print(f"Executing: {shell_display(cmd)}", flush=True)

    if config.print_command_only:
        return 0

    # stdout carries the matched groups; progress and warnings stay on stderr.
    result = subprocess.run(cmd, check=False, env=env, stdout=subprocess.PIPE, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        print(
            "find-dups exited with an error. Review the output above for unreadable "
            "or corrupted image paths.",
            file=sys.stderr,
        )
        return result.returncode

    captured = [
        paths
        for paths in (
            [path for path in group if not media_sorter.is_within(path, quarantine_dir)]
            for group in media_sorter.parse_quoted_groups(result.stdout.splitlines())
        )
        if len(paths) > 1
    ]
    digests = media_sorter.DigestCache(digest_cache_path(cache))
    groups = media_sorter.build_photo_groups(captured, digests, print_progress)
    # Damaged images never appear in find-dups groups; check them byte-for-byte.
    exclude = [*config.exclude_dirs, *media_sorter.photo_exclude_patterns(config.target, quarantine_dir)]
    matched = [path for paths in captured for path in paths]
    groups.extend(media_sorter.exact_groups_outside_matches(config.target, matched, digests, exclude, print_progress))
    # Empty or zero-filled photos hold no data: never keep one as an original.
    empty = media_sorter.find_empty_media(config.target, media_sorter.PHOTO_EXTENSIONS, exclude, print_progress)
    groups = media_sorter.drop_groups_with(groups, (group.items[0].path for group in empty)) + empty
    print_report(groups, config.include_similar)
    selected = [group for group in groups if group.exact or config.include_similar]
    file_count = sum(len(group.duplicates) for group in selected)

    if config.mode == "dry-run":
        print("Dry run complete. No files were moved or deleted.")
        return 0

    if config.mode == "quarantine":
        manifest = media_sorter.quarantine_groups(config.target.resolve(), quarantine_dir, selected, callback=print_progress)
        statuses = [entry.status for entry in manifest.entries]
        print(
            f"Moved {statuses.count('moved')} files, skipped {statuses.count('skipped')}, "
            f"failed {statuses.count('error')}. Restore manifest: {manifest.path}"
        )
        return 1 if statuses.count("error") else 0

    if not config.yes:
        confirm_delete(config.target, file_count)
    deleted, failed = delete_duplicates(selected)
    print(f"Deleted {deleted} files, failed {failed}.")
    return 1 if failed else 0


def parse_args(argv: Sequence[str] | None = None) -> DedupConfig:
    parser = argparse.ArgumentParser(
        description="Safety-first multi-device photo deduplication wrapper for find-dups.",
    )
    parser.add_argument("target", type=existing_target, help="Consolidated photos root folder.")
    parser.add_argument(
        "--cache",
        type=Path,
        default=DEFAULT_CACHE,
        help="JSON or Pickle hash DB path. Existing files are reused.",
    )
    parser.add_argument("--mode", choices=MODES, default="dry-run")
    parser.add_argument(
        "--quarantine-dir",
        type=Path,
        default=None,
        help="Destination for quarantine mode. Defaults to a sibling of the target folder.",
    )
    parser.add_argument("--algorithm", choices=ALGORITHMS, default="phash")
    parser.add_argument("--hash-size", type=positive_int, default=8)
    parser.add_argument(
        "--find-dups-bin",
        default="find-dups",
        help="Executable name or path for the duplicate_images CLI.",
    )
    parser.add_argument("--no-progress", action="store_true", help="Disable find-dups progress bars.")
    parser.add_argument("--no-parallel", action="store_true", help="Disable parallel hash computation.")
    parser.add_argument(
        "--parallel-workers",
        type=positive_int,
        default=None,
        help="Optional worker count to pass after --parallel.",
    )
    parser.add_argument(
        "--exclude-dir",
        action="append",
        default=[],
        help="Regex for subfolders to exclude. Repeat for multiple exclusions.",
    )
    parser.add_argument(
        "--max-image-pixels",
        type=positive_int,
        default=None,
        help="Forwarded to find-dups for unusually huge images.",
    )
    parser.add_argument(
        "--yes",
        action="store_true",
        help="Skip the interactive DELETE confirmation in delete mode.",
    )
    parser.add_argument(
        "--print-command-only",
        action="store_true",
        help="Validate inputs and print the find-dups command without running it.",
    )
    parser.add_argument(
        "--include-similar",
        action="store_true",
        help="Also act on similar (not byte-identical) groups, keeping the highest-resolution image. "
        "These include burst shots and edits; review them first.",
    )

    args = parser.parse_args(argv)
    if args.no_parallel and args.parallel_workers is not None:
        parser.error("--parallel-workers cannot be used with --no-parallel")

    try:
        cache = normalize_cache_path(args.cache)
    except ValueError as exc:
        parser.error(str(exc))

    quarantine_dir = args.quarantine_dir.expanduser() if args.quarantine_dir is not None else None
    exclude_dirs: list[str] = list(args.exclude_dir)
    effective_quarantine_dir = quarantine_dir or default_quarantine_dir(args.target)
    if path_is_relative_to(effective_quarantine_dir, args.target):
        # find-dups searches each file's full parent path, so anchor on the
        # absolute quarantine path rather than its folder name.
        pattern = rf"(?i)^{re.escape(str(effective_quarantine_dir.resolve()))}(?:[\\/]|$)"
        if pattern not in exclude_dirs:
            exclude_dirs.append(pattern)
        print("Warning: quarantine directory is inside the target tree; excluding it from the scan.")

    return DedupConfig(
        target=args.target,
        cache=cache,
        mode=args.mode,
        quarantine_dir=quarantine_dir,
        algorithm=args.algorithm,
        hash_size=args.hash_size,
        find_dups_executable=args.find_dups_bin,
        progress=not args.no_progress,
        parallel=not args.no_parallel,
        parallel_workers=args.parallel_workers,
        exclude_dirs=tuple(exclude_dirs),
        max_image_pixels=args.max_image_pixels,
        yes=args.yes,
        print_command_only=args.print_command_only,
        include_similar=args.include_similar,
    )


def main(argv: Sequence[str] | None = None) -> int:
    try:
        config = parse_args(argv)
        return run_deduplication(config)
    except KeyboardInterrupt:
        print("\nInterrupted by user.", file=sys.stderr)
        return 130
    except RuntimeError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
